# [application] 응용 서비스가 바깥(DB 저장소·트랜잭션)에 기대하는 모양. 실제 구현은 infrastructure에 있다.
from typing import Protocol
from uuid import UUID

from orders.domain.address import Address, AddressInput
from orders.domain.cart import CartLine, CartVariant
from orders.domain.checkout import OrderDraft, ShippingPolicy
from orders.domain.order import Order


class AddressRepositoryPort(Protocol):
    async def lock_owner(self, user_id: UUID) -> None: ...

    async def list_by_user(self, user_id: UUID, keyword: str | None, page: int, size: int) -> tuple[list[Address], int]: ...

    async def get(self, address_id: int) -> Address | None: ...

    async def count_by_user(self, user_id: UUID) -> int: ...

    async def list_all_by_user(self, user_id: UUID) -> list[Address]: ...

    async def add(self, user_id: UUID, content: AddressInput, is_default: bool) -> Address: ...

    async def update_content(self, address_id: int, content: AddressInput) -> None: ...

    async def clear_default(self, user_id: UUID) -> None: ...

    async def mark_default(self, address_id: int) -> None: ...

    async def delete(self, address_id: int) -> None: ...


class CartRepositoryPort(Protocol):
    async def lock_owner(self, user_id: UUID) -> None: ...

    async def list_lines(self, user_id: UUID) -> list[CartLine]: ...

    async def get_variant(self, variant_id: int) -> CartVariant | None: ...

    async def get_variants(self, variant_ids: list[int]) -> dict[int, CartVariant]: ...

    async def get_quantity(self, user_id: UUID, variant_id: int) -> int | None: ...

    async def paid_quantity(self, user_id: UUID, variant_id: int) -> int: ...

    async def set_quantity(self, user_id: UUID, variant_id: int, quantity: int) -> None: ...

    async def delete_item(self, user_id: UUID, variant_id: int) -> bool: ...


class TransactionPort(Protocol):
    async def commit(self) -> None: ...

    async def rollback(self) -> None: ...


class OrderRepositoryPort(Protocol):
    async def lock_owner(self, user_id: UUID) -> None: ...

    async def shipping_policy(self) -> ShippingPolicy | None: ...

    async def add(self, user_id: UUID, draft: OrderDraft) -> Order: ...

    async def get(self, order_id: UUID) -> Order | None: ...

    async def get_for_update(self, order_id: UUID) -> Order | None: ...

    async def save_status(self, order: Order) -> None: ...

    async def list_by_user(self, user_id: UUID, status: str | None, keyword: str | None,
                           page: int, size: int) -> tuple[list[Order], int]: ...


class StockPort(Protocol):
    """재고 변경 창구. 실제 구현은 P2 재고 함수(get_variants_for_update / decrease_stock / increase_stock)를 부른다."""

    async def lock(self, variant_ids: list[int]) -> None: ...

    async def decrease(self, variant_id: int, quantity: int) -> None: ...

    async def increase(self, variant_id: int, quantity: int) -> None: ...
