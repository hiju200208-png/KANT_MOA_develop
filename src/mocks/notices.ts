export function getArtistNotices(artistSlug: string, limit = 4): Notice[] {
  return NOTICES.filter((notice) => notice.artistSlug === artistSlug)
    .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt))
    .slice(0, limit);
}

/** 공지 하나. 다른 아티스트의 공지 번호로 들어오면 null */
export function getNotice(artistSlug: string, id: number): Notice | null {
  return NOTICES.find((notice) => notice.id === id && notice.artistSlug === artistSlug) ?? null;
}
